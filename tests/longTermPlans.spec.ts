test('a pre-split lesson drags directly with one aligned preview and no dialog', async ({ page }, testInfo) => {
  await seed(page); await page.goto('/')
  const card = await split(page, 2)
  await page.getByRole('group', { name:'日历视图' }).getByRole('button', { name:'日', exact:true }).click()
  const block = card.locator('.task-card').first()
  await block.scrollIntoViewIfNeeded()
  await page.locator('.calendar-surface').evaluate(element => { element.scrollTop = 40 * 22 - 100 })
  const slot = await page.locator('.day-track').first().locator('.drop-slot').nth(40).boundingBox()
  const handle = await block.locator('.drag-handle').boundingBox()
  if (!slot || !handle) throw new Error('Missing drag geometry')
  const from = {x:handle.x+handle.width/2,y:handle.y+handle.height/2}
  const to = {x:slot.x+slot.width/2,y:slot.y+slot.height/2}
  async function touch(type: string, point: {x:number;y:number}) { await block.evaluate((element, { type, point }) => { const finger = new Touch({identifier:1,target:element,clientX:point.x,clientY:point.y}); const touches=type==='touchend'?[]:[finger]; element.dispatchEvent(new TouchEvent(type,{bubbles:true,cancelable:true,touches,targetTouches:touches,changedTouches:[finger]})) },{type,point}) }
  const mobile=testInfo.project.name==='mobile-chromium'
  if (mobile) { await touch('touchstart',from); for(let i=1;i<=12;i++) await touch('touchmove',{x:from.x+(to.x-from.x)*i/12,y:from.y+(to.y-from.y)*i/12}) }
  else { await page.mouse.move(from.x,from.y); await page.mouse.down(); await page.mouse.move(to.x,to.y,{steps:12}) }
  const guide=page.locator('.drag-time-guide')
  await expect(guide).toBeVisible()
  const guideTime=await guide.getAttribute('data-time')
  await expect(page.locator('.drag-overlay')).toHaveCount(1)
  await expect.poll(async()=>Math.abs((await guide.boundingBox())!.y-(await page.locator('.drag-overlay').boundingBox())!.y)).toBeLessThanOrEqual(3)
  if(mobile) await touch('touchend',to); else await page.mouse.up()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(card).toContainText('已安排 1/2')
  const data=await saved(page)
  const lesson=data.find((item:{planAllocation?:{units:number[]}})=>item.planAllocation?.units[0]===1)
  expect(new Date(lesson.start).toTimeString().slice(0,5)).toBe(guideTime)
  expect(lesson.duration).toBe(90)
  expect(data.find((item:{id:string})=>item.id===ordinary.id)).toEqual(ordinary)
})

test('plans upload atomically and a cloud conflict replaces the complete graph only after choice', async ({ page }) => {
  await seed(page, [])
  const user={id:'00000000-0000-4000-8000-000000000006',email:'tester@example.com',aud:'authenticated',role:'authenticated'}
  const header=Buffer.from(JSON.stringify({alg:'HS256',typ:'JWT'})).toString('base64url')
  const payload=Buffer.from(JSON.stringify({sub:user.id,email:user.email,role:user.role,exp:4102444800})).toString('base64url')
  await page.addInitScript(session=>localStorage.setItem('sb-127-auth-token',JSON.stringify(session)),{access_token:`${header}.${payload}.signature`,refresh_token:'test-refresh-token',expires_in:3600,expires_at:4102444800,token_type:'bearer',user})
  let cloud:any[]=[]
  let revision=1
  let conflict=false
  await page.route('http://127.0.0.1:54321/rest/v1/workgrid_data**',async route=>{
    const method=route.request().method()
    if(method==='PATCH' && conflict) { await route.fulfill({status:200,contentType:'application/json',body:'[]'}); return }
    if(method==='PATCH') { cloud=route.request().postDataJSON().tasks; revision+=1 }
    await route.fulfill({status:200,contentType:'application/json',body:JSON.stringify({tasks:cloud,revision,updated_at:new Date().toISOString()})})
  })
  await page.goto('/')
  const card=await split(page,3)
  await expect.poll(()=>cloud.length).toBe(4)
  expect(cloud.filter(item=>item.planDefinition)).toHaveLength(1)
  expect(cloud.filter(item=>item.planAllocation)).toHaveLength(3)
  cloud=cloud.map(item=>item.planDefinition?{...item,title:'另一台设备的计划'}:item)
  revision+=1; conflict=true
  await card.getByRole('button',{name:'编辑计划 高数网课'}).click()
  const edit=page.getByRole('dialog',{name:'编辑长期计划'})
  await edit.getByLabel('计划名称').fill('本机计划修改')
  await edit.getByRole('button',{name:'保存计划'}).click()
  const choice=page.getByRole('dialog',{name:'发现同步冲突'})
  await expect(choice).toBeVisible({timeout:10000})
  await expect(page.locator('.plan-card')).toContainText('本机计划修改')
  await choice.getByRole('button',{name:'保留云端版本'}).click()
  await expect(page.locator('.plan-card')).toContainText('另一台设备的计划')
  expect((await saved(page)).filter((item:{planAllocation?:unknown})=>item.planAllocation)).toHaveLength(3)
  const expand=page.locator('.plan-card').getByRole('button',{name:'查看待安排方块（3）'})
  if(await expand.getAttribute('aria-expanded')!=='true') await expand.click()
  await expect(page.locator('.plan-card .task-card')).toHaveCount(3)
})
