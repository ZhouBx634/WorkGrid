import { expect, test, type Page } from '@playwright/test'

const key = 'workgrid.tasks.v2'
const ordinary = { id: 'ordinary', title: '原有工作', color: 'blue', duration: 60, start: null, createdAt: '2026-10-01T00:00:00.000Z', status: 'todo', completedAt: null, reminderMinutes: null, remindedAt: null, endReminder: false, endRemindedAt: null, tags: [], deletedAt: null }
async function seed(page: Page, tasks: unknown[] = [ordinary]) { await page.addInitScript(({ key, tasks }) => { if (!localStorage.getItem('plan-test-seeded')) { localStorage.setItem(key, JSON.stringify(tasks)); localStorage.setItem('plan-test-seeded', 'true') } }, { key, tasks }) }
async function saved(page: Page) { return page.evaluate(key => JSON.parse(localStorage.getItem(key) ?? '[]'), key) }
function localDateTime(date: Date) { return new Date(date.getTime() - date.getTimezoneOffset() * 60000).toISOString().slice(0, 16) }
async function createCountable(page: Page, total = 10) {
  await page.getByRole('button', { name: '新建计划', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '新建长期计划' })
  await dialog.getByLabel('计划名称').fill('高数网课')
  await dialog.getByLabel('总量', { exact: true }).fill(String(total))
  await dialog.getByLabel('每单位预计时长（分钟）').fill('90')
  await dialog.getByRole('button', { name: '保存计划' }).click()
  return page.locator('.plan-card', { hasText: '高数网课' })
}
async function split(page: Page, total = 10) {
  const card = await createCountable(page, total)
  await card.getByRole('button', { name: '拆分为可安排日程' }).click()
  await card.getByRole('button', { name: '生成待安排日程' }).click()
  return card
}
async function createDDL(page: Page) {
  const deadline = new Date(); deadline.setDate(deadline.getDate() + 5); deadline.setHours(23,59,0,0)
  await page.getByRole('button', { name: '新建计划', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '新建长期计划' })
  await dialog.getByLabel('计划名称').fill('期中作业')
  await dialog.getByLabel('计划类型').selectOption('deadline')
  await dialog.getByLabel('截止日期与时间', { exact: true }).fill(localDateTime(deadline))
  await dialog.getByRole('button', { name: '保存计划' }).click()
  return deadline
}

