  await form.getByRole('button', { name:'开始 + 结束' }).click()
  await expect(form.getByLabel('结束时间', { exact:true })).toHaveValue(localDateTime(end))
  await page.getByRole('button', { name:'创建工作方块' }).click()
  expect((await saved(page))[0].duration).toBe(95)
  expect((await saved(page))[0].start).toBe(start.toISOString())
  await page.getByRole('group', { name:'日历视图' }).getByRole('button', { name:'日', exact:true }).click()
  await page.locator('.calendar-event').click()
  const dialog = page.getByRole('dialog', { name:'编辑工作方块' })
  await dialog.getByRole('button', { name:'开始 + 时长' }).click()
  const late = new Date(start); late.setHours(23,40)
  await dialog.getByLabel('开始时间（可暂不安排）').fill(localDateTime(late))
  await dialog.getByLabel('预计时长（分钟）').fill('40')
